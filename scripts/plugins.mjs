import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

/** Which plugins this Kannabi is built with, and where each comes from.
 *
 * The list is `kannabi.plugins.json` at the repository root when that file
 * exists, and `kannabi.plugins.default.json` otherwise. The first is a
 * deployment's own and is never committed; the second is what a plain
 * checkout builds.
 *
 *   { "plugins": [
 *       { "id": "example", "repository": "https://example.org/kannabi-plugin-example.git", "ref": "v0.1.0" },
 *       { "id": "local" }
 *   ] }
 *
 * An entry with no `repository` names a plugin already in `plugins/<id>/`. One
 * with a `repository` is cloned there at `ref` by `sync`. Order is composition
 * order: a plugin comes after every plugin it requires.
 *
 *   node scripts/plugins.mjs compose   write the three generated composition files
 *   node scripts/plugins.mjs sync      fetch every listed repository, then compose and verify
 *
 * Composition stays static. Nothing is discovered: a directory under
 * `plugins/` that the list does not name is not built in.
 */
const deploymentList = 'kannabi.plugins.json';
const defaultList = 'kannabi.plugins.default.json';
export const generated = Object.freeze({
  server: 'server/plugins.generated.ts',
  web: 'web/plugins.generated.ts',
  routes: 'web/routes.generated.ts',
});

class PluginsError extends Error {}

function readList(root) {
  const file = existsSync(join(root, deploymentList)) ? deploymentList : defaultList;
  let parsed;
  try { parsed = JSON.parse(readFileSync(join(root, file), 'utf8')); }
  catch (error) { throw new PluginsError(`${file} could not be read as JSON: ${error.message}`); }
  if (parsed === null || typeof parsed !== 'object' || !Array.isArray(parsed.plugins)
    || Object.keys(parsed).some((key) => key !== 'plugins')) {
    throw new PluginsError(`${file} must be an object holding only a "plugins" array`);
  }
  const seen = new Set();
  const plugins = parsed.plugins.map((entry, index) => {
    const where = `${file}: plugins[${index}]`;
    if (entry === null || typeof entry !== 'object' || Array.isArray(entry)) throw new PluginsError(`${where} must be an object`);
    const unknown = Object.keys(entry).find((key) => !['id', 'repository', 'ref'].includes(key));
    if (unknown !== undefined) throw new PluginsError(`${where} has an unknown key "${unknown}"`);
    const { id, repository, ref } = entry;
    // The same grammar the plugin contract holds an id to; it is also a
    // directory name, so nothing else may reach the filesystem.
    if (typeof id !== 'string' || !/^[a-z][a-z0-9-]*$/.test(id)) throw new PluginsError(`${where} needs an "id" that is a lowercase token`);
    if (seen.has(id)) throw new PluginsError(`${file} lists "${id}" twice`);
    seen.add(id);
    if (repository === undefined) {
      if (ref !== undefined) throw new PluginsError(`${where} has a "ref" and no "repository"`);
      return { id };
    }
    // Neither value may be read by git as an option.
    for (const [name, value] of [['repository', repository], ['ref', ref]]) {
      if (typeof value !== 'string' || value === '' || value.startsWith('-') || /\s/.test(value)) {
        throw new PluginsError(`${where} needs a "${name}"; a fetched plugin is always pinned to a ref`);
      }
    }
    return { id, repository, ref };
  });
  return { file, plugins };
}

/** The ids the list names, in order. */
export const listed = (root) => readList(root).plugins.map(({ id }) => id);

const banner = (file) => `// Generated by \`pnpm plugins:compose\` from ${file}. Do not edit: change the list and compose again.\n`;

/** Write the three files through which core learns the installed plugins.
 * Each is plain imports, so what is composed is typechecked like any code. */
export function compose(root) {
  const { file, plugins } = readList(root);
  const has = (id, path) => existsSync(join(root, 'plugins', id, path));
  for (const { id, repository } of plugins) {
    if (!has(id, 'index.ts')) {
      throw new PluginsError(`${file} lists "${id}" and plugins/${id}/index.ts does not exist`
        + (repository ? '; run `pnpm plugins:sync` to fetch it' : ''));
    }
  }
  const webbed = plugins.filter(({ id }) => has(id, 'web/index.tsx') || has(id, 'web/index.ts'));
  const routed = plugins.filter(({ id }) => has(id, 'web/routes.ts'));
  const name = ({ id }) => `plugin${plugins.findIndex((plugin) => plugin.id === id)}`;
  const write = (path, lines) => {
    const next = banner(file) + lines.join('\n') + '\n';
    const target = join(root, path);
    // Left alone when nothing changed, so a watcher does not restart for it.
    if (!existsSync(target) || readFileSync(target, 'utf8') !== next) writeFileSync(target, next);
  };
  write(generated.server, [
    "import type { PluginDefinition } from './plugin.js';",
    ...plugins.map((plugin) => `import ${name(plugin)} from '../plugins/${plugin.id}/index.js';`),
    '',
    `export const definitions: readonly PluginDefinition[] = [${plugins.map(name).join(', ')}];`,
  ]);
  write(generated.web, [
    "import type { WebPlugin } from './plugin';",
    ...webbed.map((plugin) => `import ${name(plugin)} from '../plugins/${plugin.id}/web/index';`),
    '',
    `export const plugins: readonly WebPlugin[] = [${webbed.map(name).join(', ')}];`,
  ]);
  write(generated.routes, [
    "import type { RouteConfigEntry } from '@react-router/dev/routes';",
    ...routed.map((plugin) => `import * as ${name(plugin)} from '../plugins/${plugin.id}/web/routes';`),
    '',
    `export const pluginRoutes: RouteConfigEntry[] = [${routed.map((plugin) => `...${name(plugin)}.routes`).join(', ')}];`,
    `export const pluginGroupRoutes: RouteConfigEntry[] = [${routed.map((plugin) => `...${name(plugin)}.groupRoutes`).join(', ')}];`,
  ]);
  return { file, plugins: plugins.map(({ id }) => id) };
}

function git(cwd, ...args) {
  try { return execFileSync('git', args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim(); }
  catch (error) { throw new PluginsError(`git ${args.join(' ')} failed in ${cwd}: ${(error.stderr || error.message).trim()}`); }
}

/** The commit a ref names: a tag first, then a branch of the remote, then
 * anything else git can resolve, such as a commit id. */
function commitOf(directory, ref) {
  for (const candidate of [`refs/tags/${ref}`, `refs/remotes/origin/${ref}`, ref]) {
    try {
      return execFileSync('git', ['rev-parse', '--verify', '--quiet', `${candidate}^{commit}`],
        { cwd: directory, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
    } catch { /* try the next reading */ }
  }
  throw new PluginsError(`"${ref}" names no commit in ${directory}`);
}

/** Bring every fetched plugin to its pinned ref. A clone with local changes is
 * refused and never overwritten: it may be somebody's work in progress. */
export function sync(root, log = () => {}) {
  const { file, plugins } = readList(root);
  for (const { id, repository, ref } of plugins) {
    if (repository === undefined) continue;
    const directory = join(root, 'plugins', id);
    if (!existsSync(directory)) {
      git(root, 'clone', '--quiet', '--no-checkout', '--', repository, directory);
    } else {
      if (!existsSync(join(directory, '.git'))) {
        throw new PluginsError(`plugins/${id} exists and is not a clone, and ${file} says to fetch it from ${repository}`);
      }
      const origin = git(directory, 'remote', 'get-url', 'origin');
      if (origin !== repository) throw new PluginsError(`plugins/${id} was cloned from ${origin}, and ${file} names ${repository}`);
      if (git(directory, 'status', '--porcelain') !== '') {
        throw new PluginsError(`plugins/${id} has local changes; commit or discard them before syncing`);
      }
      git(directory, 'fetch', '--quiet', '--tags', '--prune', 'origin');
    }
    const commit = commitOf(directory, ref);
    git(directory, 'checkout', '--quiet', '--detach', commit);
    log(`${id}: ${ref} (${commit.slice(0, 12)}) from ${repository}`);
  }
  return compose(root);
}

/** Ask the contract itself whether this set of plugins may be composed: a
 * missing requirement or an unsupported contract is refused here, before a
 * build, with the message startup would give. */
function verify(root) {
  try {
    execFileSync(process.execPath, ['--import', 'tsx', '--input-type=module', '-e', "await import('./server/composition.ts')"],
      { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
  } catch (error) {
    const message = /Error: (.*)/.exec(error.stderr ?? '')?.[1] ?? (error.stderr || error.message).trim();
    throw new PluginsError(`These plugins cannot be composed: ${message}`);
  }
}

if (process.argv[1] && import.meta.filename === process.argv[1]) {
  const command = process.argv[2];
  try {
    if (command === 'compose') {
      compose(process.cwd());
    } else if (command === 'sync') {
      const { file, plugins } = sync(process.cwd(), (line) => console.log(line));
      verify(process.cwd());
      console.log(`Composed from ${file}: ${plugins.join(', ') || 'no plugins'}`);
    } else {
      throw new PluginsError('Usage: node scripts/plugins.mjs compose | sync');
    }
  } catch (error) {
    if (!(error instanceof PluginsError)) throw error;
    console.error(error.message);
    process.exit(1);
  }
}
